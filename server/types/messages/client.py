"""Messages originating from the client"""

from typing import Literal, TypedDict, Union

from typing_extensions import NotRequired


class AcceptPartyInvite(TypedDict):
    """Accept a party invite.

    The sender must have first created an invite by sending a `InviteToParty`
    command.

    **Example**
    ```json
    {
        "command": "accept_party_invite",
        "sender_id": 1234
    }
    ```
    """

    command: Literal["accept_party_invite"]

    sender_id: int
    """ID of the player who sent the invite."""


Admin = Union[
    "AdminBroadcast",
    "AdminCloseFA",
    "AdminCloseLobby",
    "AdminJoinChannel",
]


class AdminBroadcast(TypedDict):
    """Send a message to all connected players.

    **Example**
    ```json
    {
        "command": "admin",
        "action": "broadcast",
        "message": "Hello World"
    }
    ```
    """

    command: Literal["admin"]
    action: Literal["broadcast"]

    message: str
    """Message text to send. Can contain certain HTML styling tags.

    Only applies to `broadcast`.
    """


